-- Integration messages table for storing raw inbound/outbound HL7, FHIR, or custom messages
-- from sandbox simulator gateways or real interfaces.
--
-- Security posture: RLS enabled and forced; only system or authorized staff can access messages.

BEGIN;

CREATE TABLE integration_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid REFERENCES tenants(id) ON DELETE CASCADE,
  integration_id text NOT NULL,
  direction text NOT NULL CHECK (direction IN ('inbound', 'outbound')),
  message_type text NOT NULL,
  payload text NOT NULL,
  status text NOT NULL CHECK (status IN ('received', 'processed', 'failed')),
  error_message text,
  simulated boolean NOT NULL DEFAULT false,
  source text,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE integration_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE integration_messages FORCE ROW LEVEL SECURITY;

CREATE POLICY integration_messages_tenant_isolation ON integration_messages
  FOR ALL
  USING (tenant_id = app.current_tenant())
  WITH CHECK (tenant_id = app.current_tenant());

CREATE POLICY integration_messages_system_access ON integration_messages
  FOR ALL
  USING (app.actor_kind() = 'system')
  WITH CHECK (app.actor_kind() = 'system');

COMMENT ON TABLE integration_messages IS 'Audit log of inbound and outbound integration messages (HL7 v2, FHIR, etc.).';
COMMENT ON COLUMN integration_messages.simulated IS 'true when the message was generated by or sent to a sandbox simulator gateway.';

COMMIT;
